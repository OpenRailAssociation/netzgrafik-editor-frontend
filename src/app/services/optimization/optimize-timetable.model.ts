import {TrainrunSection} from "../../models/trainrunsection.model";
import {SolutionKpis} from "./optimization-policy.model";

export interface OptimizeTimetableOptions {
  /** Search strategy used to produce proposals. */
  engine?: "heuristic" | "cp-sat";
  /** Hard limit: maximum number of tracks per edge (node - node). */
  maxTracksPerSection: number;
  /** Selected node ids. Empty => whole network is optimized. */
  selectedNodeIds?: number[];
  /** Canonical edge ids restricting optimization to a selected trainrun's corridor. */
  selectedCorridorEdgeIds?: string[];
  /** Search time budget in milliseconds (default 1000). */
  timeBudgetMs?: number;
  /** Random seed – a different seed lets the user continue with another search path. */
  seed?: number;
  /** Start assignment (e.g. from a previous proposal) to continue the search. */
  startAssignment?: Record<string, number>;
  /** Window above the connection time counted as optional connection (default 5). */
  optionalConnectionWindow?: number;
  /** Maximum number of proposals returned (default and upper limit 5). */
  maxProposals?: number;
  /** Emit a bounded step-by-step optimization trace to the browser console. */
  debugTrace?: boolean;
  /** Hard constraints and objective preferences selected in the director. */
  policy?: import("./optimization-policy.model").OptimizationPolicy;
}

export type TimeField =
  | "sourceDeparture"
  | "sourceArrival"
  | "targetDeparture"
  | "targetArrival"
  | "travelTime"
  | "backwardTravelTime";

export interface TimeChange {
  trainrunSectionId: number;
  trainrunId: number;
  trainrunName: string;
  sourceNodeId: number;
  targetNodeId: number;
  sourceNodeName: string;
  targetNodeName: string;
  field: TimeField;
  oldValue: number;
  newValue: number;
}

export interface EdgeTrackKpi {
  edgeId: string;
  inScope: boolean;
  fromNodeName: string;
  toNodeName: string;
  tracksBefore: number;
  tracksAfter: number;
  trackSegments?: {start: number; end: number; tracks: number}[];
  trackSegmentsBefore?: {start: number; end: number; tracks: number}[];
  trackSegmentsAfter?: {start: number; end: number; tracks: number}[];
}

export type TrackConflictBlockerReason =
  | "selection-boundary"
  | "no-shift-range"
  | "no-free-variable";

export interface TrackConflictBlocker {
  sectionId: number;
  trainrunName: string;
  fromNodeName: string;
  toNodeName: string;
  times: {
    forwardDeparture: {display: string; locked: boolean};
    forwardArrival: {display: string; locked: boolean};
    forwardTravelTime: {display: string; locked: boolean};
    backwardDeparture: {display: string; locked: boolean};
    backwardArrival: {display: string; locked: boolean};
    backwardTravelTime: {display: string; locked: boolean};
  };
  reasons: TrackConflictBlockerReason[];
}

export interface ImmutableTrackConflict extends EdgeTrackKpi {
  blockingSections: TrackConflictBlocker[];
}

export interface OptimizeTimetableKpi extends SolutionKpis {
  /** Edges exceeding the track limit (exact estimator) before / after. */
  edgesOverLimitBefore: number;
  edgesOverLimitAfter: number;
  /** Highest track count over all changed edges before / after. */
  maxTracksBefore: number;
  maxTracksAfter: number;
  /** Highest node track count before / after. */
  maxNodeTracksBefore: number;
  maxNodeTracksAfter: number;
  /** Minimum stop-time violations before / after, regardless of hard-rule state. */
  minimumStopViolationsBefore: number;
  minimumStopViolationsAfter: number;
  /** Sum of total travel time changes (minutes, all trainruns and directions). */
  totalTravelTimeDelta: number;
  /** Number of optional connections before / after. */
  optionalConnectionsBefore: number;
  optionalConnectionsAfter: number;
  /** Sum of absolute shifts (minutes). */
  sumAbsShift: number;
  changedTrainruns: number;
  changedTimes: number;
}

export interface OptimizeTimetableSolution {
  id: number;
  label: string;
  /** Exact hard-rule validation; infeasible candidates may be previewed, never committed. */
  valid: boolean;
  /** Candidate generated by relaxing locks and selection scope for diagnosis only. */
  diagnosticOnly?: boolean;
  kpi: OptimizeTimetableKpi;
  edges: EdgeTrackKpi[];
  changes: TimeChange[];
  assignment: Record<string, number>;
}

export interface OptimizeTimetableResult {
  /** Search strategy that produced this result. */
  engine?: "heuristic" | "cp-sat";
  /** Both strict and relaxed finite CP-SAT models are exhausted. */
  searchExhausted?: boolean;
  baselineKpi: OptimizeTimetableKpi;
  baselineEdges: EdgeTrackKpi[];
  /** Exact scoped track conflicts with no movable dependent variable. */
  immutableTrackConflicts?: ImmutableTrackConflict[];
  solutions: OptimizeTimetableSolution[];
  /** Best infeasible alternatives, available for explicitly expanded comparison. */
  infeasibleSolutions?: OptimizeTimetableSolution[];
  /** Candidates searched outside the current locks and selection scope for diagnosis. */
  diagnosticSolutions?: OptimizeTimetableSolution[];
  freeVariables: number;
  freeShiftVariables: number;
  freeTravelTimeVariables: number;
  fixedTravelTimeVariables: number;
  travelTimeLockBlockedVariables: number;
  departureTimeLockBlockedVariables: number;
  arrivalTimeLockBlockedVariables: number;
  scopeBlockedTravelTimeVariables: number;
  noRangeTravelTimeVariables: number;
  fixedChains: number;
  iterations: number;
  evaluatedCandidates: number;
  runtimeMs: number;
  /** Edges violating the limit before optimization (surrogate). */
  initialEdgesOverLimit: number;
  /** Best internal search state for warming up another attempt; it may be infeasible. */
  searchBestAssignment?: Record<string, number>;
  message?: string;
}

/** Index of the four times of a section in the internal time arrays. */
export const SRC_DEP = 0;
export const SRC_ARR = 1;
export const TGT_DEP = 2;
export const TGT_ARR = 3;

export const TIME_FIELDS: TimeField[] = [
  "sourceDeparture",
  "sourceArrival",
  "targetDeparture",
  "targetArrival",
];

export interface SectionTimes {
  section: TrainrunSection;
  times: number[];
  travelTime: number;
  backwardTravelTime: number;
}
